"""بانک کلمات و رنگ‌های بازی نقاشی حدسی دو نفره."""

import random

WORDS = [
    "خورشید", "ماه", "ستاره", "ابر", "درخت", "گل", "گربه", "سگ", "ماهی",
    "پرنده", "خانه", "دوچرخه", "هواپیما", "کشتی", "قطار", "اتومبیل",
    "کتاب", "توپ", "گیتار", "چتر", "عینک", "کلاه", "ساعت", "پروانه",
    "زنبور", "فیل", "شیر", "زرافه", "پنگوئن", "خرگوش", "میمون", "پیتزا",
    "همبرگر", "بستنی", "سیب", "موز", "هویج", "تخم‌مرغ", "قاشق", "چاقو",
    "کوه", "رودخانه", "قلعه", "تاج", "کلید", "قفل", "شمع", "کیک",
    "مداد", "قیچی",
]

# پالت ۱۰ رنگ برای نقاش
COLORS = [
    "#111111",  # مشکی
    "#E53935",  # قرمز
    "#FB8C00",  # نارنجی
    "#FDD835",  # زرد
    "#43A047",  # سبز
    "#00ACC1",  # فیروزه‌ای
    "#1E88E5",  # آبی
    "#8E24AA",  # بنفش
    "#EC407A",  # صورتی
    "#6D4C41",  # قهوه‌ای
]


def pick_round_words(count_options: int = 12) -> tuple[str, list[str]]:
    """یک کلمهٔ هدف و لیستی از گزینه‌ها (شامل خود کلمه) برمی‌گرداند، به‌هم‌ریخته."""
    target = random.choice(WORDS)
    pool = [w for w in WORDS if w != target]
    distractors = random.sample(pool, min(count_options - 1, len(pool)))
    options = distractors + [target]
    random.shuffle(options)
    return target, options
